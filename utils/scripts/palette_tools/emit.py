"""
The files generated from a palette: its LaTeX value layer, its LaTeX role layer, and its CSS block.

Every generated text states its source and its generator, so that an edit is made in the palette
and never in the output. The LaTeX layers are written beside the palette file, as
``colors-values.tex`` when the palette declares values, and ``colors-roles.tex`` when it binds
roles. The CSS block is
written into each web page between two markers naming the palette.
"""

from __future__ import annotations

from pathlib import Path

from palette_tools.spec import PaletteSpec

#: Names of the generated LaTeX layers, beside the palette file.
VALUES_FILE = "colors-values.tex"
ROLES_FILE = "colors-roles.tex"

#: Media query of each mode in CSS.
MEDIA = {"dark": "prefers-color-scheme: dark"}

GENERATOR = "utils/scripts/build_palette.py"
RULE = "% " + "=" * 98


def _header(path: str, layer: str) -> list[str]:
    return [
        f"% FILE: {path}",
        RULE,
        f"% GENERATED from palette.yml by {GENERATOR}: edit the palette, then run the generator.",
        f"% {layer}",
    ]


def latex_values(spec: PaletteSpec, path: str) -> str:
    """
    The ``\\definecolor`` layer of a palette.

    Parameters
    ----------
    spec : PaletteSpec
        The palette.
    path : str
        The path of the generated file from the vault root, printed in its header.

    Returns
    -------
    str
        The LaTeX source, one ``\\definecolor`` per token, grouped by layer.
    """
    lines = _header(path, "The value of each token, grouped by layer.")
    for layer in spec.layers:
        lines += ["", f"% ----- {layer.name}: {layer.gloss}"]
        width = max(len(t.name) for t in layer.tokens)
        for token in layer.tokens:
            use = f"{token.rung} -- {token.use}" if token.rung else token.use
            lines.append(f"\\definecolor{{{token.name}}}{{HTML}}{{{token.value}}}"
                         f"{' ' * (width - len(token.name))} % {use}")
    return "\n".join(lines) + "\n"


def latex_roles(spec: PaletteSpec, path: str) -> str:
    """
    The ``\\colorlet`` layer of a palette, to be loaded after its value layer.

    Parameters
    ----------
    spec : PaletteSpec
        The palette, which binds at least one role.
    path : str
        The path of the generated file from the vault root, printed in its header.

    Returns
    -------
    str
        The LaTeX source, one ``\\colorlet`` per role, in load order.
    """
    lines = _header(path, "The token bound to each role. Load it after the values: "
                          "\\colorlet copies a value when it is read.")
    lines.append("")
    targets = [f"{r.of}!{r.tint}" if r.tint else r.of for r in spec.roles]
    width = max(len(r.name) + len(t) for r, t in zip(spec.roles, targets))
    for role, target in zip(spec.roles, targets):
        pad = " " * (width - len(role.name) - len(target))
        lines.append(f"\\colorlet{{{role.name}}}{{{target}}}{pad} % {role.use}")
    return "\n".join(lines) + "\n"


def css_block(spec: PaletteSpec, source: str, indent: str) -> str:
    """
    The CSS custom properties of a palette, with one media block per mode.

    Parameters
    ----------
    spec : PaletteSpec
        The palette, which declares at least one CSS name.
    source : str
        The path of the palette from the vault root, printed in the opening marker.
    indent : str
        The indentation of the opening marker, applied to every line.

    Returns
    -------
    str
        The block, from its opening marker to its closing marker, without a final newline.
    """
    base = spec.values()
    lines = [f"/* palette: {source} -- generated by {GENERATOR}; edit the palette */", ":root {"]
    lines += [f"  --{name}: #{base[target]};" for name, target in spec.css.items()]
    lines.append("}")
    for mode, query in MEDIA.items():
        if mode not in spec.modes:
            continue
        shifted = spec.values(mode)
        changed = [(n, t) for n, t in spec.css.items() if shifted[t] != base[t]]
        lines += [f"@media ({query}) {{", "  :root {"]
        lines += [f"    --{name}: #{shifted[target]};" for name, target in changed]
        lines += ["  }", "}"]
    lines.append("/* palette: end */")
    return "\n".join(indent + line for line in lines)


def outputs(spec: PaletteSpec, root: Path) -> dict[Path, str]:
    """
    The LaTeX layers generated from a palette, by output path.

    Parameters
    ----------
    spec : PaletteSpec
        The palette.
    root : Path
        The vault root, against which the header paths are written.

    Returns
    -------
    dict[Path, str]
        The text of each generated file.
    """
    folder = spec.path.parent
    out: dict[Path, str] = {}
    if spec.layers:
        values = folder / VALUES_FILE
        out[values] = latex_values(spec, values.relative_to(root).as_posix())
    if spec.roles:
        roles = folder / ROLES_FILE
        out[roles] = latex_roles(spec, roles.relative_to(root).as_posix())
    return out
